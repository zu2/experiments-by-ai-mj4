def mark(base, m):
    """Puts the mark at the top right without moving the base glyph when it
    fits: the whole mark with a free row under it, or a dakuten of one row.
    Otherwise one row of the glyph (a repeated one if there is one) is
    removed and its top moves down a row, so the bottom row stays."""
    height = 3 if m[2] != "..." else 2
    g = GLYPHS[base]
    if all(g[y][x] == "." for y in range(height + 1) for x in range(4, 8)):
        rows = [list(r) for r in g]
    elif height == 2 and all(g[0][x] == "." for x in range(4, 8)):
        rows = [list(r) for r in g]
        rows[0][5] = rows[0][7] = "#"
        return ["".join(r) for r in rows]
    else:
        body = list(g[:7])
        drop = next((y for y in range(1, 7) if body[y] == body[y - 1]), None)
        if drop is None:
            drop = min(range(1, 7), key=lambda y: body[y].count("#"))
        del body[drop]
        rows = [list("........")] + [list(r) for r in body] + [list("........")]
        for y in range(2):
            for x in range(4, 8):
                rows[y][x] = "."
    for y in range(3):
        for x in range(3):
            if m[y][x] == "#":
                rows[y][5 + x] = "#"
    return ["".join(r) for r in rows]


for v, b in VOICED.items():
    GLYPHS[v] = mark(b, DAKU)
for v, b in SEMI.items():
    GLYPHS[v] = mark(b, HANDAKU)
