def stick(h):
    rows = [".#."]
    mid = (h - 1) // 2
    for y in range(1, h - 1):
        rows.append(".#." if y == mid else "#.#")
    rows.append(".#.")
    return rows


def blank():
    return [["."] * W for _ in range(H)]


def put(g, art, x0, y0):
    for y, row in enumerate(art):
        for x, c in enumerate(row):
            if c == "#":
                g[y0 + y][x0 + x] = "#"


def bigcircle():
    g = []
    cx, cy = 7.5, 7.5
    for y in range(16):
        r = ""
        for x in range(14):
            d = ((x - 6.5) ** 2 + (y - 7.5) ** 2) ** 0.5
            r += "#" if 6.0 <= d < 7.0 or 3.5 <= d < 4.5 or d < 1.6 else "."
        g.append(r)
    return g


