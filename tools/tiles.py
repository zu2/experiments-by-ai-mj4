def back():
    g = blank()
    # Match the small tile backs: a pattern distinguishes them from haku.
    for y in range(H - 1):
        for x in range(W - 1):
            if ((x // 2) + (y // 2)) & 1:
                g[y][x] = "#"
    return g, [G] * 6


ORDER = list(range(34)) + [("red", 4), ("red", 13), ("red", 22), "back"]


def all_tiles():
    out = []
    for o in ORDER:
        if o == "back":
            out.append(("back",) + back())
        elif isinstance(o, tuple):
            out.append(("r%d" % o[1],) + tile(o[1], red=True))
        else:
            out.append((str(o),) + tile(o))
    return out
