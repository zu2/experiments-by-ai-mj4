"""Pack the six source WAVs into 8 kHz, 5-bit linear PCM for the BM Jr. DAC.

Generation only: numpy and scipy are needed; rebuilding the game uses data.s.
"""
from pathlib import Path
import wave
import numpy as np
from scipy.signal import resample_poly, butter, sosfilt, iirpeak, lfilter
from math import gcd

root = Path(__file__).resolve().parents[1] / 'voice'
out = ['; Generated by tools/voice.py. Eight 5-bit samples per five bytes, MSB first.']
for name in ('pon', 'chi', 'kan', 'ron', 'tsumo', 'riichi'):
    with wave.open(str(root / 'source' / (name + '.wav'))) as f:
        assert f.getnchannels() == 1 and f.getsampwidth() == 2
        rate = f.getframerate()
        x = np.frombuffer(f.readframes(f.getnframes()), dtype='<i2').astype(float)
    divisor = gcd(rate, 8000)
    x = resample_poly(x, 8000 // divisor, rate // divisor)
    x -= x.mean()
    peak = max(abs(x))
    active = np.flatnonzero(abs(x) > peak * .025)
    x = x[active[0]:active[-1] + 1]
    # Gentle -3 dB low shelf, then +4 dB presence around 2.5 kHz (Q=1.1).
    low = sosfilt(butter(1, 250, fs=8000, output='sos'), x)
    x -= (1 - 10**(-3 / 20)) * low
    b, a = iirpeak(2500, Q=1.1, fs=8000)
    x = lfilter(a + (10**(4 / 20) - 1) * b, a, x)
    x *= 14.0 / max(abs(x))
    # Fade ends to the middle DAC level; avoid switching a full offset at once.
    x[:80] *= np.linspace(0, 1, 80)
    x[-80:] *= np.linspace(1, 0, 80)
    q = np.clip(np.rint(x + 16), 0, 31).astype(np.uint8)
    q = np.pad(q, (0, (-len(q)) % 8), constant_values=16)
    packed = np.packbits(((q[:, None] >> np.arange(4, -1, -1)) & 1).reshape(-1))
    (root / (name + '.pcm')).write_bytes(packed.tobytes())
    out += ['snd_' + name + ':', '\t.byte\t$FF', '\t.word\tvoice_' + name + '_end']
    for i in range(0, len(packed), 16):
        out.append('\t.byte\t' + ','.join('$%02X' % v for v in packed[i:i+16]))
    out.append('voice_' + name + '_end:')
    print('%s: %d bytes, %.3f s' % (name, len(packed), len(q) / 8000))
(root / 'data.s').write_text('\n'.join(out) + '\n')
