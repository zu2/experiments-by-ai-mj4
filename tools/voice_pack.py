"""Lossless per-word delta/Huffman compression of packed 5-bit PCM."""
from pathlib import Path
from collections import Counter
import heapq
root = Path(__file__).resolve().parents[1] / 'voice'
words = {}
# The code of a delta depends on the previous delta: voice_tree0 after 0, 1 or
# 31 (and for the first sample), voice_tree otherwise.
counts = [Counter(), Counter()]
for name in ('pon', 'chi', 'kan', 'ron', 'tsumo', 'riichi'):
    raw = (root / (name + '.pcm')).read_bytes()
    bits = ''.join(f'{v:08b}' for v in raw)
    q = [int(bits[i:i+5], 2) for i in range(0, len(bits), 5)]
    delta = [(v - (q[i-1] if i else 16)) & 31 for i, v in enumerate(q)]
    ctx = [0] + [0 if d in (0, 1, 31) else 1 for d in delta[:-1]]
    words[name] = (raw, delta, ctx)
    for c, d in zip(ctx, delta):
        counts[c][d] += 1
out = ['; Generated by tools/voice_pack.py.']
# A node is two bytes: a leaf (0..31) or the low byte of a node in the same page.
trees = ['; Generated by tools/voice_pack.py; delta Huffman trees chosen by the previous delta.']
codes = []
for c, label in ((0, 'voice_tree0'), (1, 'voice_tree')):
    queue = [(n, i, v) for i, (v, n) in enumerate(sorted(counts[c].items()))]
    heapq.heapify(queue)
    serial = 32
    while len(queue) > 1:
        a, _, x = heapq.heappop(queue)
        b, _, y = heapq.heappop(queue)
        heapq.heappush(queue, (a+b, serial, (x, y)))
        serial += 1
    tree = []
    code = {}
    def visit(node, prefix):
        if isinstance(node, int):
            code[node] = prefix
            return 128 | node
        index = len(tree) // 2
        tree.extend([0, 0])
        tree[2*index] = visit(node[0], prefix + '0')
        tree[2*index+1] = visit(node[1], prefix + '1')
        return index
    visit(queue[0][2], '')
    codes.append(code)
    for node in range(len(tree)//2):
        if node == 0:
            trees.append(label + ':')
        trees.append('%s_%d:' % (label, node))
        children = [str(v & 31) if v & 128 else '<%s_%d' % (label, v) for v in tree[2*node:2*node+2]]
        trees.append(' .byte ' + ','.join(children))
    print('%s: %d bytes' % (label, len(tree)))
total = 0
for name, (raw, delta, ctx) in words.items():
    bits = ''.join(codes[c][d] for c, d in zip(ctx, delta))
    bits += '0' * (-len(bits) % 8)
    packed = bytes(int(bits[i:i+8], 2) for i in range(0, len(bits), 8))
    (root / (name + '.lz')).write_bytes(packed)
    assert len(raw) % 5 == 0 and len(raw) <= 0x2F00 - 0x2100, 'PCM_BUF overruns the BSS'
    out += ['snd_' + name + ':', ' .byte $FF', ' .word %d' % len(raw)]
    for i in range(0, len(packed), 16):
        out.append(' .byte ' + ','.join('$%02X' % v for v in packed[i:i+16]))
    total += len(packed)
    print('%s: %d -> %d bytes' % (name, len(raw), len(packed)))
(root / 'packed.s').write_text('\n'.join(out) + '\n')
(root / 'trees.s').write_text('\n'.join(trees) + '\n')
print('compressed total:', total, 'bytes; scratch:', max(len(v[0]) for v in words.values()))
