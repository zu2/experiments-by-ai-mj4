"""Lossless per-word delta/Huffman compression of packed 5-bit PCM."""
from pathlib import Path
from collections import Counter
import heapq
root = Path(__file__).resolve().parents[1] / 'voice'
words = {}
counts = Counter()
for name in ('pon', 'chi', 'kan', 'ron', 'tsumo', 'riichi'):
    raw = (root / (name + '.pcm')).read_bytes()
    bits = ''.join(f'{v:08b}' for v in raw)
    q = [int(bits[i:i+5], 2) for i in range(0, len(bits), 5)]
    delta = [(v - (q[i-1] if i else 16)) & 31 for i, v in enumerate(q)]
    words[name] = (raw, delta)
    counts.update(delta)
queue = [(n, i, v) for i, (v, n) in enumerate(sorted(counts.items()))]
heapq.heapify(queue)
serial = 32
while len(queue) > 1:
    a, _, x = heapq.heappop(queue)
    b, _, y = heapq.heappop(queue)
    heapq.heappush(queue, (a+b, serial, (x, y)))
    serial += 1
tree = []
codes = {}
def visit(node, prefix):
    if isinstance(node, int):
        codes[node] = prefix
        return 128 | node
    index = len(tree) // 2
    tree.extend([0, 0])
    tree[2*index] = visit(node[0], prefix + '0')
    tree[2*index+1] = visit(node[1], prefix + '1')
    return index
visit(queue[0][2], '')
out = ['; Generated by tools/voice_pack.py; shared delta Huffman tree.']
for node in range(len(tree)//2):
    if node == 0:
        out.append('voice_tree:')
    out.append('voice_node%d:' % node)
    children = [str(v & 31) if v & 128 else 'voice_node%d' % v for v in tree[2*node:2*node+2]]
    out.append(' .word ' + ','.join(children))
total = 0
for name, (raw, delta) in words.items():
    bits = ''.join(codes[v] for v in delta)
    bits += '0' * (-len(bits) % 8)
    packed = bytes(int(bits[i:i+8], 2) for i in range(0, len(bits), 8))
    (root / (name + '.lz')).write_bytes(packed)
    samples = len(raw) * 8 // 5
    assert samples <= 0x3300 - 0x2100, 'PCM_BUF overruns the BSS'
    out += ['snd_' + name + ':', ' .byte $FF', ' .word %d' % samples]
    for i in range(0, len(packed), 16):
        out.append(' .byte ' + ','.join('$%02X' % v for v in packed[i:i+16]))
    total += len(packed)
    print('%s: %d -> %d bytes' % (name, len(raw), len(packed)))
(root / 'packed.s').write_text('\n'.join(out) + '\n')
print('compressed total:', total, 'bytes; tree:', len(tree)*2, 'bytes; scratch:', max(len(v[0]) for v in words.values()) * 8 // 5)
