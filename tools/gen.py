import sys
import tiles
from font import GLYPHS

GLYPHS["<"] = [".......#", "......##", ".....#.#", "....#..#", ".......#", ".......#", ".......#", "........"]
GLYPHS[">"] = ["#.......", "##......", "#.#.....", "#..#....", "#.......", "#.......", "#.......", "........"]
GLYPHS["-"] = ["........", "........", "........", ".######.", "........", "........", "........", "........"]
GLYPHS[":"] = ["........", "..##....", "..##....", "........", "..##....", "..##....", "........", "........"]
GLYPHS["Z"] = ["#######.", ".....##.", "....##..", "...##...", "..##....", ".##.....", "#######.", "........"]
GLYPHS["X"] = ["##...##.", ".##.##..", "..###...", "...#....", "..###...", ".##.##..", "##...##.", "........"]
GLYPHS["="] = ["........", "........", ".######.", "........", ".######.", "........", "........", "........"]
GLYPHS["ォ"] = ["........", "........", "....##..", "#######.", "...###..", "..#.##..", "...###..", "........"]
GLYPHS["?"] = [".#####..", "##...##.", ".....##.", "...###..", "...##...", "........", "...##...", "........"]
GLYPHS["+"] = ["........", "...#....", "...#....", ".#####..", "...#....", "...#....", "........", "........"]
GLYPHS["▶"] = [".#......", ".##.....", ".###....", ".####...", ".###....", ".##.....", ".#......", "........"]
ORDER = " 0123456789-TRKPC<>"
codes = {c: i for i, c in enumerate(ORDER)}
used = set("+▶")
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.rstrip("\n")
    if line and not line.startswith("#"):
        used |= set(line.split("\t")[-1])
for c in sorted(GLYPHS):
    if c not in codes and c in used:
        codes[c] = len(codes)


def tile_data(name, g, col):
    rows = []
    for y in range(24):
        bits = 0
        for x in range(16):
            if g[y][x] == "#" or x == 15 or y == 23:
                bits |= 0x8000 >> x
        rows += [bits >> 8, bits & 0xff]
    if name in ("r4", "r13", "r22"):
        rows[0] |= 0xE0
        rows[2] |= 0xC0
        rows[4] |= 0x80
    return [v ^ 255 for v in rows]


def byte_lines(data, per=16):
    out = []
    for i in range(0, len(data), per):
        out.append("\t.byte\t" + ",".join("$%02X" % b for b in data[i:i + per]))
    return out


def main():
    out = ["; generated by gen.py"]
    ts = tiles.all_tiles()
    out.append("tileaddr:")
    for i in range(len(ts)):
        out.append("\t.word\ttile%d" % i)
    row_values = []
    row_ids = {}
    packed_tiles = []
    for name, g, col in ts:
        raw = tile_data(name, g, col)
        indices = []
        for y in range(24):
            row = tuple(raw[2*y:2*y+2])
            if row not in row_ids:
                row_ids[row] = len(row_values)
                row_values.append(row)
            indices.append(row_ids[row])
        packed_tiles.append(indices)
    assert len(row_values) < 128
    for i, indices in enumerate(packed_tiles):
        out.append('tile%d:' % i)
        packed=[]
        y=0
        while y<len(indices):
            pair=y+1<len(indices) and indices[y]==indices[y+1]
            packed.append(indices[y] | (128 if pair else 0))
            y+=2 if pair else 1
        out += byte_lines(packed)
    out.append('tile_rows:')
    out += byte_lines([v for row in row_values for v in row])
    out.append("font:")
    for c, i in sorted(codes.items(), key=lambda kv: kv[1]):
        g = GLYPHS[c]
        assert g[7] == "........"
        out += byte_lines([int(r.replace("#", "1").replace(".", "0"), 2) for r in g[:7]], 7)
    out.append("CH_0\t.equ\t%d" % codes["0"])
    out.append("CH_SP\t.equ\t%d" % codes[" "])
    out.append("CH_PLUS\t.equ\t%d" % codes["+"])
    out.append("CH_MINUS\t.equ\t%d" % codes["-"])
    out.append("CH_ARROW_L\t.equ\t%d" % codes["<"])
    out.append("CH_ARROW_R\t.equ\t%d" % codes[">"])
    out.append("CH_TURN\t.equ\t%d" % codes["▶"])
    for c in "TRKPC":
        out.append("CH_%s\t.equ\t%d" % (c, codes[c]))
    yaku = {}
    strings = []
    for line in open(sys.argv[1], encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        label, text = line.split("\t", 1)
        if label == "yaku":
            num, text = text.split("\t", 1)
            label = "y_%s" % num
            yaku[int(num)] = label
        if any(c not in codes for c in text):
            sys.exit("missing glyph in " + label)
        strings.append((label, text))
    # Share identical strings and suffixes, including their terminator.
    strings.append(("y_none", ""))
    roots = []
    for label, text in sorted(strings, key=lambda item: -len(item[1])):
        root = next((r for r in roots if r[0].endswith(text)), None)
        if root is None:
            root = (text, {})
            roots.append(root)
        root[1].setdefault(len(root[0])-len(text), []).append(label)
    for text, aliases in roots:
        for offset, value in enumerate([codes[c] for c in text]+[255]):
            out.extend(label+":" for label in aliases.get(offset, []))
            out += byte_lines([value])
    out.append("yaku_names:")
    for n in range(max(yaku) + 1):
        out.append("\t.word\t%s" % yaku.get(n, "y_none"))
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


main()
