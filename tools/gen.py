import sys
import tiles
import huff
from font import GLYPHS

GLYPHS["<"] = [".......#", "......##", ".....#.#", "....#..#", ".......#", ".......#", ".......#", "........"]
GLYPHS[">"] = ["#.......", "##......", "#.#.....", "#..#....", "#.......", "#.......", "#.......", "........"]
GLYPHS["-"] = ["........", "........", "........", ".######.", "........", "........", "........", "........"]
GLYPHS[":"] = ["........", "..##....", "..##....", "........", "..##....", "..##....", "........", "........"]
GLYPHS["Z"] = ["#######.", ".....##.", "....##..", "...##...", "..##....", ".##.....", "#######.", "........"]
GLYPHS["X"] = ["##...##.", ".##.##..", "..###...", "...#....", "..###...", ".##.##..", "##...##.", "........"]
GLYPHS["="] = ["........", "........", ".######.", "........", ".######.", "........", "........", "........"]
GLYPHS["ォ"] = ["........", "........", "....##..", "#######.", "...###..", "..#.##..", "...###..", "........"]
GLYPHS["?"] = [".#####..", "##...##.", ".....##.", "...###..", "...##...", "........", "...##...", "........"]
GLYPHS["+"] = ["........", "...#....", "...#....", ".#####..", "...#....", "...#....", "........", "........"]
GLYPHS["▶"] = [".#......", ".##.....", ".###....", ".####...", ".###....", ".##.....", ".#......", "........"]
ORDER = " 0123456789-TRKPC<>"
codes = {c: i for i, c in enumerate(ORDER)}
used = set("+▶")
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.rstrip("\n")
    if line and not line.startswith("#"):
        used |= set(line.split("\t")[-1])
for c in sorted(GLYPHS):
    if c not in codes and c in used:
        codes[c] = len(codes)


TILE_JUMP = 127


def tile_data(name, g, col):
    rows = []
    for y in range(24):
        bits = 0
        for x in range(16):
            if g[y][x] == "#" or x == 15 or y == 23:
                bits |= 0x8000 >> x
        rows += [bits >> 8, bits & 0xff]
    if name in ("r4", "r13", "r22"):
        rows[0] |= 0xE0
        rows[2] |= 0xC0
        rows[4] |= 0x80
    return [v ^ 255 for v in rows]


def byte_lines(data, per=16):
    out = []
    for i in range(0, len(data), per):
        out.append("\t.byte\t" + ",".join("$%02X" % b for b in data[i:i + per]))
    return out


def main():
    out = ["; generated by gen.py"]
    ts = tiles.all_tiles()
    # tileaddr: the rows of each tile as indices of tile_rows; bit 7 makes
    # the row two rows. TILE_JUMP and an address of an earlier tile's bytes:
    # the rest of the rows are read from there (drawtile).
    row_values = []
    row_ids = {}
    packed_tiles = []
    for name, g, col in ts:
        raw = tile_data(name, g, col)
        indices = []
        for y in range(24):
            row = tuple(raw[2*y:2*y+2])
            if row not in row_ids:
                row_ids[row] = len(row_values)
                row_values.append(row)
            indices.append(row_ids[row])
        packed = []
        y = 0
        while y < len(indices):
            pair = y+1 < len(indices) and indices[y] == indices[y+1]
            packed.append(indices[y] | (128 if pair else 0))
            y += 2 if pair else 1
        packed_tiles.append((indices, packed))
    assert len(row_values) < TILE_JUMP
    # placed: (tile, bytes) where a byte is a number or ('jump', tile, offset).
    placed = []

    def rows_from(t, k, n):
        rows = []
        while len(rows) < n:
            if k == len(placed[t][1]):
                return None
            b = placed[t][1][k]
            if isinstance(b, tuple):
                t, k = b[1], b[2]
                continue
            rows += [b & 127] * (2 if b & 128 else 1)
            k += 1
        return rows[:n] if len(rows) == n else None

    for i, (indices, packed) in enumerate(packed_tiles):
        best = None
        y = 0
        for j in range(len(packed)):
            need = indices[y:]
            if len(packed) - j > 3:
                for t, data in placed:
                    for k in range(len(data)):
                        if not isinstance(data[k], tuple) and rows_from(t, k, len(need)) == need:
                            best = (j, t, k)
                            break
                    if best:
                        break
            if best:
                break
            y += 2 if packed[j] & 128 else 1
        data = packed[:best[0]] + [('jump', best[1], best[2])] if best else packed
        placed.append((i, data))
        assert rows_from(i, 0, 24) == indices
    out.append("tileaddr:")
    for i in range(len(ts)):
        out.append("\t.word\ttile%d" % i)
    for i, data in placed:
        out.append('tile%d:' % i)
        lits = []
        for k, b in enumerate(data):
            if isinstance(b, tuple):
                out += byte_lines(lits)
                lits = []
                out.append("\t.byte\t%d" % TILE_JUMP)
                out.append("\t.word\ttile%d+%d" % (b[1], b[2]))
            else:
                lits.append(b)
        out += byte_lines(lits)
    out.append('tile_rows:')
    out += byte_lines([v for row in row_values for v in row])
    out.append("TILE_JUMP\t.equ\t%d" % TILE_JUMP)
    # font_set: 7 rows of 1 byte of each character (huff.py, img_decode).
    glyphs = []
    for c, i in sorted(codes.items(), key=lambda kv: kv[1]):
        g = GLYPHS[c]
        assert g[7] == "........"
        glyphs.append([int(r.replace("#", "1").replace(".", "0"), 2) for r in g[:7]])
    out += huff.assembly("font_set", glyphs, False)
    out.append("CH_0\t.equ\t%d" % codes["0"])
    out.append("CH_SP\t.equ\t%d" % codes[" "])
    out.append("CH_PLUS\t.equ\t%d" % codes["+"])
    out.append("CH_MINUS\t.equ\t%d" % codes["-"])
    out.append("CH_ARROW_L\t.equ\t%d" % codes["<"])
    out.append("CH_ARROW_R\t.equ\t%d" % codes[">"])
    out.append("CH_TURN\t.equ\t%d" % codes["▶"])
    for c in "TRKPC":
        out.append("CH_%s\t.equ\t%d" % (c, codes[c]))
    yaku = {}
    strings = []
    for line in open(sys.argv[1], encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        label, text = line.split("\t", 1)
        if label == "yaku":
            num, text = text.split("\t", 1)
        if any(c not in codes for c in text):
            sys.exit("missing glyph in " + label)
        if label == "yaku":
            yaku[int(num)] = text
        else:
            strings.append((label, text))
    # yaku_text holds the yaku names in the order of their numbers (an empty
    # name for a number without one). The other strings share identical
    # strings and suffixes, including their terminator.
    roots = [(yaku.get(n, ""), {}) for n in range(max(yaku) + 1)]
    roots[0][1][0] = ["yaku_text"]
    for label, text in sorted(strings, key=lambda item: -len(item[1])):
        root = next((r for r in roots if r[0].endswith(text)), None)
        if root is None:
            root = (text, {})
            roots.append(root)
        root[1].setdefault(len(root[0])-len(text), []).append(label)
    for text, aliases in roots:
        # The last character has bit 7; an empty string is one 255.
        values = [codes[c] for c in text] or [255]
        values[-1] |= 128
        for offset, value in enumerate(values):
            out.extend(label+":" for label in aliases.get(offset, []))
            out += byte_lines([value])
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


main()
